#!/usr/bin/env python3
"""Writes pairs.json and pairs.csv: which traces each question is asked of, and the right
answer on each. This is the test matrix the runner and the grading use.

    python3 make_pairs.py            # needs questions.json, symptoms.json, scenarios.json, runs/

Each question is asked of at most PER_QUESTION traces of its program:
  1. every trace where its symptom is present, and every trace that cannot show it (the
     events it requires were not recorded), so no positive test is lost;
  2. the program's healthy run (--fault none), the cleanest negative;
  3. the program's other faults, picked at random until there are PER_QUESTION traces. The
     seed is the symptom and program, so adding a question never changes the others' picks.
     Faults that list the symptom as "don't care" are skipped, since they are never graded.

Every pair is asked in both wordings (a and b), so the number of answers per system is
2 x the number of pairs here, times the repeats.

pairs.json names each pair's fault and truth: like runs/index.csv, never give it to the
systems under test.
"""

import csv
import json
import random
import sys
from collections import Counter, defaultdict
from pathlib import Path

HERE = Path(__file__).resolve().parent
PER_QUESTION = 5

# (symptom, program, fault) pairs where the symptom cannot be told from a kernel trace, though no
# event group is missing: a thread spin-waiting on a flag (busy_wait) and one computing nonstop
# (cpu_hog) are both pinned, 100% in user mode, with no system calls and no wake-ups. "Cannot
# tell" is the right answer there; on the other traces no thread looks like that, so "no" is.
UNSEEABLE = {
    ("busy_wait", "crunch", "busy_wait"): "a spin-wait on a flag and nonstop computation look the same "
                                          "in a kernel trace",
    ("busy_wait", "crunch", "cpu_hog"): "a spin-wait on a flag and nonstop computation look the same "
                                        "in a kernel trace",
}


def main() -> int:
    symptoms = {s["id"]: s for s in json.loads((HERE / "symptoms.json").read_text())["symptoms"]}
    faults = {(p["program"], f["name"]): f
              for p in json.loads((HERE / "scenarios.json").read_text()) for f in p["faults"]}
    runs = defaultdict(list)
    for r in csv.DictReader((HERE / "runs" / "index.csv").open()):
        runs[r["program"]].append(r)
    questions = [q for q in json.loads((HERE / "questions.json").read_text())["questions"]
                 if q["wording"] == "precise"]

    def truth(sid: str, run: dict) -> str:
        fault = faults[(run["program"], run["fault"])]
        missing = {g for g in (run["events_left_out"] + "+" + run["events_unavailable"]).split("+")
                   if g}
        if set(symptoms[sid]["requires"]) & missing:
            return "cannot_see"
        if (sid, run["program"], run["fault"]) in UNSEEABLE:
            return "cannot_see"
        if sid in fault["present"]:
            return "present"
        if sid in fault["dont_care"]:
            return "dont_care"
        return "absent"

    pairs, problems = [], []
    for q in questions:
        labelled = sorted(((truth(q["symptom"], r), r) for r in runs[q["program"]]),
                          key=lambda x: x[1]["run_id"])
        keep = [(t, r, "positive" if t == "present" else "cannot_see")
                for t, r in labelled if t in ("present", "cannot_see")]
        keep += [(t, r, "healthy") for t, r in labelled if t == "absent" and r["fault"] == "none"]
        others = [(t, r) for t, r in labelled if t == "absent" and r["fault"] != "none"]
        random.Random(f"{q['symptom']}:{q['program']}").shuffle(others)
        keep += [(t, r, "other_fault") for t, r in others[:max(0, PER_QUESTION - len(keep))]]
        if not any(k[2] in ("positive", "cannot_see") for k in keep):
            problems.append(f"{q['question']} has no trace where its symptom is present")
        if len(keep) > PER_QUESTION:
            problems.append(f"{q['question']} has {len(keep)} traces")
        for t, r, role in keep:
            pairs.append({
                "question": q["question"], "symptom": q["symptom"], "program": q["program"],
                "category": q["category"], "hub": q["hub"], "v1": q["v1"],
                "run_id": r["run_id"], "trace": f"runs/{r['run_id']}/trace",
                "fault": r["fault"], "events_left_out": r["events_left_out"],
                "truth": t, "role": role,
            })

    (HERE / "pairs.json").write_text(json.dumps({
        "about": "The test matrix: each question with the traces it is asked of and the right "
                 "answer on each. Generated by make_pairs.py. Never give this file to the "
                 "systems under test: it names each trace's fault.",
        "per_question": PER_QUESTION,
        "pairs": pairs,
    }, indent=2) + "\n")
    with (HERE / "pairs.csv").open("w", newline="") as f:
        w = csv.DictWriter(f, fieldnames=list(pairs[0]))
        w.writeheader()
        w.writerows(pairs)

    for p in problems:
        print("  " + p)
    truths = Counter(p["truth"] for p in pairs)
    print(f"wrote pairs.json and pairs.csv: {len(pairs)} pairs for {len(questions)} questions "
          f"({', '.join(f'{v} {k}' for k, v in truths.most_common())}); "
          f"{2 * len(pairs)} with both wordings; {len(problems)} problem(s)")
    return 1 if problems else 0


if __name__ == "__main__":
    sys.exit(main())
