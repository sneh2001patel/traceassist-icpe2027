#!/usr/bin/env python3
"""Writes the two readable lists at the repository root, from the bench's own data files:

  QUESTIONS.md  all 112 questions (56 questions x 2 wordings), with the traces each was asked of
  SYMPTOMS.md   the 48 symptoms, what counts as present, and which programs and faults show them

Sources: questions.json, symptoms.json, scenarios.json, pairs.json, verdict.py. Edit those
(or the scripts that generate them), not the .md files.  Usage: python3 make_lists.py
"""
import collections
import json
from pathlib import Path

import verdict

HERE = Path(__file__).resolve().parent
ROOT = HERE.parent
CATEGORIES = ["comprehension", "root_cause", "dependency", "quantitative", "remediation"]
LABEL = {c: c.replace("_", " ").capitalize() for c in CATEGORIES}
GROUPS = [("timing", "Timing"), ("waiting", "Waiting"), ("cpu", "CPU"),
          ("syscalls_io", "System calls and I/O"), ("lifecycle", "Lifecycle"),
          ("pipelines", "Pipelines"), ("unexpected", "Unexpected behaviour")]


def cell(text):
    return str(text).replace("|", "\\|").replace("\n", " ")


def load():
    questions = json.loads((HERE / "questions.json").read_text())
    symptoms = json.loads((HERE / "symptoms.json").read_text())
    scenarios = json.loads((HERE / "scenarios.json").read_text())
    pairs = json.loads((HERE / "pairs.json").read_text())["pairs"]
    return questions, symptoms, scenarios, pairs


def questions_md(questions, pairs):
    by_q = collections.defaultdict(lambda: {"a": None, "b": None})
    for q in questions["questions"]:
        by_q[q["question"]]["a" if q["wording"] == "precise" else "b"] = q
    truth = collections.defaultdict(collections.Counter)
    for p in pairs:
        truth[p["question"]][p["truth"]] += 1
    order = sorted(by_q, key=lambda q: int(q[1:]))
    n_pairs = collections.Counter(p["truth"] for p in pairs)

    out = ["# Questions",
           "",
           "Every question asked in the paper's evaluation. Generated by `bench/make_lists.py` from "
           "`bench/questions.json` and `bench/pairs.json`.",
           "",
           f"There are {len(order)} questions, one for each symptom and program that can show it, "
           f"each in two wordings, so {2 * len(order)} in all. Both wordings name the program.",
           "",
           "- **a. Precise:** states exactly what counts, with a threshold where the symptom has a size.",
           "- **b. Everyday:** phrased the way a user would ask, with a user's vagueness.",
           "",
           f"Each question is asked of up to five traces of its program: every trace where the symptom is "
           f"present or cannot be seen, the healthy run, then other faults of that program, picked at random "
           f"with a fixed seed. That makes {len(pairs)} question–trace pairs: {n_pairs['present']} present, "
           f"{n_pairs['absent']} absent and {n_pairs['cannot_see']} that the trace cannot show. With both "
           f"wordings, each system gave {2 * len(pairs)} answers. The **Traces** column gives, for each "
           "question, the number of traces where its symptom is present / absent / cannot be seen. "
           "`bench/pairs.csv` lists which traces those are.",
           "",
           "Every system received this instruction after every question:",
           "",
           f"> {verdict.INSTRUCTION}",
           "",
           "**Grader's note:** " + " ".join(questions.get("grader_notes", [])),
           "",
           "| Category | Single-hub | Multi-hub | Total |",
           "|---|---|---|---|"]
    count = collections.Counter((by_q[q]["a"]["category"], by_q[q]["a"]["hub"]) for q in order)
    for c in CATEGORIES:
        out.append(f"| {LABEL[c]} | {count[(c, 'single')]} | {count[(c, 'multi')]} | "
                   f"{count[(c, 'single')] + count[(c, 'multi')]} |")
    out.append(f"| **All** | {sum(v for (c, h), v in count.items() if h == 'single')} | "
               f"{sum(v for (c, h), v in count.items() if h == 'multi')} | {len(order)} |")

    for c in CATEGORIES:
        qs = [q for q in order if by_q[q]["a"]["category"] == c]
        out += ["", f"## {LABEL[c]} ({len(qs)})", "",
                "| # | Symptom | Program | Hub | a. Precise | b. Everyday | Traces |",
                "|---|---|---|---|---|---|---|"]
        for q in qs:
            a, b, t = by_q[q]["a"], by_q[q]["b"], truth[q]
            out.append(f"| {q} | {cell(a['symptom_name'])} | `{a['program']}` | {a['hub']} | {cell(a['text'])} | "
                       f"{cell(b['text'])} | {t['present']} / {t['absent']} / {t['cannot_see']} |")
    return "\n".join(out) + "\n"


def symptoms_md(symptoms, scenarios, questions, pairs):
    shows = collections.defaultdict(list)   # symptom -> program:fault where it is present
    for prog in scenarios:
        for f in prog["faults"]:
            for s in f["present"]:
                shows[s].append(f"`{prog['program']} --fault {f['name']}`")
    asked_in = collections.defaultdict(set)
    for q in questions["questions"]:
        asked_in[q["symptom"]].add((int(q["question"][1:]), q["question"], q["program"]))
    cannot = {p["symptom"] for p in pairs if p["truth"] == "cannot_see"}
    groups = {g: [s for s in symptoms["symptoms"] if s["group"] == g] for g, _ in GROUPS}

    out = ["# Symptoms",
           "",
           "The performance symptoms the bench covers. Generated by `bench/make_lists.py` from "
           "`bench/symptoms.json` and `bench/scenarios.json`.",
           "",
           f"There are {len(symptoms['symptoms'])} symptoms in {len(GROUPS)} groups. Each has a written "
           "criterion for **present**. Each is made present by at least one fault of the nine bench "
           "programs (`<program> --fault <fault>`). On every other trace of that program it is absent, "
           "unless the program's answer key marks it *don't care*.",
           "",
           "| Group | Symptoms |",
           "|---|---|"]
    for g, label in GROUPS:
        out.append(f"| {label} | {len(groups[g])} |")
    out.append(f"| **All** | {len(symptoms['symptoms'])} |")
    out += ["", "Events a symptom needs, beyond those every trace has:", ""]
    for k, v in symptoms["event_groups"].items():
        out.append(f"- `{k}`: {v}")

    for g, label in GROUPS:
        out += ["", f"## {label} ({len(groups[g])})", "",
                "| Symptom | Present when | How users ask | Shown by | Questions |",
                "|---|---|---|---|---|"]
        for s in groups[g]:
            notes = []
            if s["requires"]:
                notes.append("needs " + ", ".join(f"`{e}`" for e in s["requires"]) + " events")
            if s["id"] in cannot:
                notes.append("some traces cannot show it")
            name = f"**{cell(s['name'])}** (`{s['id']}`)" + (f"<br>*{'; '.join(notes)}*" if notes else "")
            asked = "; ".join(f"“{cell(a)}”" for a in s.get("asked", []))
            qs = ", ".join(f"{q} (`{p}`)" for _, q, p in sorted(asked_in[s["id"]]))
            out.append(f"| {name} | {cell(s['criterion'])} | {asked} | {'<br>'.join(shows[s['id']])} | "
                       f"{qs} ({s['category'].replace('_', ' ')}, {s['hub']}-hub) |")
    return "\n".join(out) + "\n"


def main():
    questions, symptoms, scenarios, pairs = load()
    (ROOT / "QUESTIONS.md").write_text(questions_md(questions, pairs))
    (ROOT / "SYMPTOMS.md").write_text(symptoms_md(symptoms, scenarios, questions, pairs))
    print(f"wrote {ROOT / 'QUESTIONS.md'} and {ROOT / 'SYMPTOMS.md'}")


if __name__ == "__main__":
    main()
